#!/usr/bin/env python3
"""
Simple example of loading and analyzing particle trajectory data.

This script demonstrates basic analysis that can be performed on the 
trajectory data generated by pyDEME_DFCSlump.py.
"""

import csv
import math

def load_trajectories(filename):
    """Load trajectory data from CSV file."""
    trajectories = {}  # particle_id -> list of (time, x, y, z)
    
    with open(filename, 'r') as f:
        reader = csv.DictReader(f)
        for row in reader:
            particle_id = int(row['particle_id'])
            time = float(row['time'])
            x = float(row['x'])
            y = float(row['y'])
            z = float(row['z'])
            
            if particle_id not in trajectories:
                trajectories[particle_id] = []
            trajectories[particle_id].append((time, x, y, z))
    
    return trajectories

def calculate_displacement(trajectory):
    """Calculate total displacement for a particle."""
    if len(trajectory) < 2:
        return 0.0
    
    start_pos = trajectory[0][1:4]  # (x, y, z)
    end_pos = trajectory[-1][1:4]
    
    dx = end_pos[0] - start_pos[0]
    dy = end_pos[1] - start_pos[1]
    dz = end_pos[2] - start_pos[2]
    
    return math.sqrt(dx**2 + dy**2 + dz**2)

def calculate_path_length(trajectory):
    """Calculate total path length traveled by a particle."""
    if len(trajectory) < 2:
        return 0.0
    
    total_length = 0.0
    for i in range(1, len(trajectory)):
        prev_pos = trajectory[i-1][1:4]
        curr_pos = trajectory[i][1:4]
        
        dx = curr_pos[0] - prev_pos[0]
        dy = curr_pos[1] - prev_pos[1]
        dz = curr_pos[2] - prev_pos[2]
        
        total_length += math.sqrt(dx**2 + dy**2 + dz**2)
    
    return total_length

def main():
    # Load the trajectory data
    filename = 'OUT_slump_V1/particle_trajectories.csv'
    
    print("=" * 60)
    print("Particle Trajectory Analysis Example")
    print("=" * 60)
    print()
    
    try:
        trajectories = load_trajectories(filename)
    except FileNotFoundError:
        print(f"Error: File '{filename}' not found.")
        print("Please run the simulation first: python pyDEME_DFCSlump.py")
        return
    
    print(f"Loaded trajectories for {len(trajectories)} particles")
    print()
    
    # Analyze each particle
    print("Particle Analysis:")
    print("-" * 60)
    print(f"{'ID':<5} {'Frames':<8} {'Displacement':<15} {'Path Length':<15}")
    print("-" * 60)
    
    for particle_id in sorted(trajectories.keys())[:10]:  # Show first 10
        trajectory = trajectories[particle_id]
        displacement = calculate_displacement(trajectory)
        path_length = calculate_path_length(trajectory)
        
        print(f"{particle_id:<5} {len(trajectory):<8} {displacement:<15.2f} {path_length:<15.2f}")
    
    if len(trajectories) > 10:
        print(f"... and {len(trajectories) - 10} more particles")
    
    print("-" * 60)
    print()
    
    # Find particle with maximum displacement
    max_displacement = 0.0
    max_particle = None
    for particle_id, trajectory in trajectories.items():
        displacement = calculate_displacement(trajectory)
        if displacement > max_displacement:
            max_displacement = displacement
            max_particle = particle_id
    
    print(f"Particle with maximum displacement: {max_particle} ({max_displacement:.2f} units)")
    
    # Calculate average displacement
    avg_displacement = sum(calculate_displacement(traj) for traj in trajectories.values()) / len(trajectories)
    print(f"Average displacement: {avg_displacement:.2f} units")
    
    print()
    print("=" * 60)
    print("Tip: Use visualize_trajectories.py to create plots!")
    print("Example: python visualize_trajectories.py --particles 0,5,10")
    print("=" * 60)

if __name__ == '__main__':
    main()
