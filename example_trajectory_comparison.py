#!/usr/bin/env python3
"""
Example demonstrating how to use compare_trajectory_runs.py to analyze
GPU stochasticity across multiple DFC slump test runs.

This script creates synthetic trajectory data to demonstrate the comparison tool.
For real data, you would use trajectory files generated by pyDEME_DFCSlump.py
from multiple simulation runs.
"""

import os
import sys
import subprocess
import tempfile
import math
import random

def create_synthetic_trajectory(filename, num_particles=50, num_frames=100, 
                               time_step=0.05, noise_level=0.0, seed=None):
    """
    Create a synthetic trajectory file that simulates slump test motion.
    
    Args:
        filename: Output CSV filename
        num_particles: Number of particles to track
        num_frames: Number of time frames
        time_step: Time between frames
        noise_level: Amount of random noise to add (simulates GPU stochasticity)
        seed: Random seed for reproducibility
    """
    if seed is not None:
        random.seed(seed)
    
    with open(filename, 'w') as f:
        f.write("time,particle_id,x,y,z\n")
        
        for particle_id in range(num_particles):
            # Initial position in cone-like arrangement
            angle = (particle_id / num_particles) * 2 * math.pi
            radius = 30 + (particle_id % 10) * 5
            initial_x = radius * math.cos(angle)
            initial_y = 150 + (particle_id % 5) * 10
            initial_z = radius * math.sin(angle)
            
            # Simulate slump: radial expansion and downward motion
            for frame in range(num_frames):
                t = frame * time_step
                
                # Physics-based motion
                expansion_factor = 1.0 + 0.5 * (1 - math.exp(-t))
                fall_distance = 0.5 * 9.81 * t * t * 0.1
                
                # Add stochastic noise
                x = initial_x * expansion_factor + noise_level * random.uniform(-1, 1)
                y = max(0, initial_y - fall_distance) + noise_level * random.uniform(-1, 1)
                z = initial_z * expansion_factor + noise_level * random.uniform(-1, 1)
                
                f.write(f"{t},{particle_id},{x},{y},{z}\n")

def main():
    print("=" * 80)
    print("TRAJECTORY COMPARISON DEMONSTRATION")
    print("=" * 80)
    print()
    print("This example demonstrates how to use compare_trajectory_runs.py to")
    print("measure GPU stochasticity in DFC slump test simulations.")
    print()
    
    # Create temporary directory for test data
    with tempfile.TemporaryDirectory() as temp_dir:
        print(f"Creating synthetic trajectory data in: {temp_dir}")
        print()
        
        # Create baseline run (deterministic)
        baseline_file = os.path.join(temp_dir, "run1_trajectories.csv")
        create_synthetic_trajectory(baseline_file, num_particles=50, 
                                    noise_level=0.0, seed=42)
        print("✓ Created baseline run (run 1) - deterministic")
        
        # Create comparison runs with small stochastic variations
        # These simulate GPU arithmetic non-associativity effects
        comparison_files = []
        for run_idx in range(2, 6):
            filename = os.path.join(temp_dir, f"run{run_idx}_trajectories.csv")
            create_synthetic_trajectory(filename, num_particles=50,
                                       noise_level=0.5, seed=42+run_idx)
            comparison_files.append(filename)
            print(f"✓ Created run {run_idx} with noise_level=0.5")
        
        print()
        print("-" * 80)
        print("Running trajectory comparison...")
        print("-" * 80)
        print()
        
        # Run the comparison tool
        cmd = [
            "python",
            "compare_trajectory_runs.py",
            "--baseline", baseline_file,
            "--runs"
        ] + comparison_files
        
        try:
            result = subprocess.run(cmd, check=True)
        except FileNotFoundError:
            print("Error: compare_trajectory_runs.py not found in current directory")
            print("Make sure you're running this from the pyDEME_tests directory")
            return 1
        except subprocess.CalledProcessError as e:
            print(f"Error running comparison: {e}")
            return 1
        
        print()
        print("=" * 80)
        print("WHAT THIS SHOWS")
        print("=" * 80)
        print()
        print("In this example:")
        print("  • Run 1 is the deterministic baseline (no noise)")
        print("  • Runs 2-5 have small random perturbations (noise_level=0.5)")
        print()
        print("The 'Relative Deviation %' metric shows the trajectory stochasticity")
        print("as a percentage of the total particle motion. This is the key metric")
        print("for assessing whether GPU-induced variations are acceptable.")
        print()
        print("For real DFC simulations, you would:")
        print("  1. Run pyDEME_DFCSlump.py multiple times")
        print("  2. Collect the particle_trajectories.csv from each run")
        print("  3. Use compare_trajectory_runs.py to quantify variations")
        print()
        print("Example with real data:")
        print("  python compare_trajectory_runs.py \\")
        print("      --baseline OUT_slump_V1/particle_trajectories.csv \\")
        print("      --runs OUT_slump_V*/particle_trajectories.csv")
        print()
    
    return 0

if __name__ == '__main__':
    sys.exit(main())
